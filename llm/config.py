"""모델·학습 하이퍼파라미터.

모델 크기 · 학습 설정 같은 "숫자 손잡이" 를 한 곳에 모아 둔다.
model.py · train.py 는 여기서 값을 꺼내 쓰기만 한다 → 실험할 때 이 파일만 고치면 된다.
"""

# dataclass: 값만 담는 클래스를 짧게 쓰게 해 주는 표준 라이브러리 기능.
# 원래는 __init__ 에 필드마다 self.이름 = 이름 을 손으로 적어야 하는데, 이걸 대신 자동으로 만들어 준다.
# 표준 라이브러리라 따로 설치할 필요 없이 불러오기만 하면 된다.
from dataclasses import dataclass


# 클래스 위에 붙이는 표시(데코레이터) — 클래스를 "이렇게 만들어 달라" 고 지정하는 문법.
# 이게 붙으면 아래 필드 목록을 보고 __init__(생성자) · __repr__(출력용 문자열) · __eq__(비교)를
# 자동으로 만들어 준다 → ModelConfig(n_layer=8) 처럼 원하는 값만 바꿔서 만들 수 있게 된다
@dataclass
class ModelConfig:
    """트랜스포머 모델의 크기를 정하는 값들. 실제 사용은 4단계 model.py 에서."""

    # 필드 형식: `이름: 타입 = 기본값`
    # 타입(: int)은 사람이 보라고 붙이는 힌트일 뿐 실행 중에 실제로 검사하지는 않는다

    # 토크나이저가 아는 토큰(글자·조각) 개수 = 모델이 고를 수 있는 "단어" 수.
    # 3단계에서 토크나이저를 만들어야 정확히 정해진다 → 지금은 임시값
    vocab_size: int = 256

    # 모델이 한 번에 보는 토큰 개수 (context length).
    # 길수록 앞 내용을 많이 기억하지만 attention 계산량이 길이의 제곱으로 늘어난다
    block_size: int = 128

    # 토큰 하나를 나타내는 벡터의 길이 (embedding 차원).
    # 클수록 토큰마다 담을 수 있는 정보가 많지만 모델도 커진다
    n_embd: int = 128

    # attention 을 몇 갈래(head)로 나눠 볼지. 각 head 는 n_embd / n_head 칸씩 나눠 가진다
    # n_embd(128) 를 나누어 떨어지게 하면서 작은 모델에 무난한 값
    n_head: int = 4

    # 트랜스포머 블록을 몇 층 쌓을지. 층이 깊을수록 복잡한 패턴을 배우지만 느려진다
    n_layer: int = 4

    # 학습 중 값 일부를 일부러 0 으로 지우는 비율 (0.1 = 10%).
    # 학습 데이터를 통째로 외워 버리는 것(과적합)을 막는 장치. 추론 때는 꺼진다
    dropout: float = 0.1

    # __post_init__: dataclass 가 자동 생성한 __init__ 이 끝난 "직후" 에 불리는 함수.
    # 값이 잘못 들어온 걸 객체 생성 순간에 잡아낸다
    def __post_init__(self):
        # n_embd 를 n_head 개로 "똑같이" 쪼개 쓰기 때문에 나누어 떨어지지 않으면 모델을 못 만든다.
        # assert 조건, "메시지": 조건이 False 면 그 자리에서 메시지와 함께 에러를 낸다
        assert self.n_embd % self.n_head == 0, "n_embd 는 n_head 로 나누어 떨어져야 한다"


@dataclass
class TrainConfig:
    """모델을 어떻게 학습시킬지 정하는 값들. 실제 사용은 5단계 train.py 에서."""

    # 한 학습 스텝에서 동시에 처리하는 데이터 개수.
    # 크면 한 스텝의 평균이 안정적이지만 GPU 메모리를 그만큼 더 먹는다.
    # 2 의 거듭제곱이 GPU 메모리 정렬에 유리해서 이 범위(16~64)를 많이 쓴다
    batch_size: int = 32

    # 파라미터를 한 스텝마다 얼마나 크게 움직일지 정하는 보폭.
    # 너무 크면 최적값을 지나쳐서 튕기고, 너무 작으면 학습이 지나치게 느리다.
    # Adam 계열 옵티마이저에서 흔히 쓰는 시작값 (지수 표기법으로 0.0003)
    learning_rate: float = 3e-4

    # 학습을 총 몇 스텝 돌릴지.
    max_iters: int = 3000

    # 몇 스텝마다 한 번씩 "지금 얼마나 잘 배우고 있나" 점검(평가)할지.
    eval_interval: int = 300

    # 점검할 때 배치를 몇 번 뽑아서 평균낼지.
    # 한 번만 뽑으면 그 배치가 우연히 쉬웠는지 어려웠는지에 따라 값이 들쭉날쭉하다 →
    # 여러 번 뽑아 평균 내면 안정적인 값을 얻는다.
    eval_iters: int = 50
