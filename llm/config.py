"""모델·학습 하이퍼파라미터.

모델 크기 · 학습 설정 같은 "숫자 손잡이" 를 한 곳에 모아 둔다.
model.py · train.py 는 여기서 값을 꺼내 쓰기만 한다 → 실험할 때 이 파일만 고치면 된다.
(왜 한 곳에 모으나: 같은 숫자를 파일마다 따로 적어 두면 한 곳만 바꿨을 때 나머지가 어긋나기 때문 — 문서 1단계 읽을 것 1번)
"""

# dataclass: 값만 담는 상자(클래스)를 짧게 만들게 해 주는 표준 라이브러리 기능.
# 원래는 __init__ 에 필드마다 self.이름 = 이름 을 손으로 적어야 하는데, 그걸 대신 만들어 준다.
# 표준 라이브러리라 따로 설치할 필요 없이 불러오기만 하면 된다.
from dataclasses import dataclass


# 클래스 바로 위에 붙이는 표시(데코레이터). 이걸 붙이면 아래에 나열한 필드를 보고
# __init__(상자를 만드는 함수) · __repr__(출력할 때 안이 보이게) · __eq__(값 비교) 를 파이썬이 자동으로 만들어 준다.
# → ModelConfig(n_layer=8) 처럼 바꾸고 싶은 값만 넣어서 상자를 만들 수 있게 된다.
@dataclass()
class ModelConfig:
    """트랜스포머 모델의 크기를 정하는 값들. 실제 사용은 4단계 model.py 에서."""

    # 필드 형식: `이름: 타입 = 기본값`
    # 타입(: int)은 사람이 보라고 붙이는 힌트일 뿐이고, 실행 중에 실제로 검사하지는 않는다.

    # 모델이 아는 글자(토큰)가 몇 종류인가 = 글자 번호가 0 ~ vocab_size-1 까지.
    # 글자 번호 → 숫자 줄 표의 "줄 수" 를 정하려면 이 값을 알아야 한다.
    # 3단계 토크나이저에서 train.txt 의 글자를 세어 확정한 값(69). 데이터를 바꾸면 다시 센다.
    vocab_size: int = 69

    # 모델이 한 번에 볼 수 있는 글자 수의 최댓값 (context length).
    # 글자끼리 서로 비교하는 계산이 글자 수의 제곱으로 늘어나서(10글자 100번, 128글자 16384번) 무한정 키울 수 없다.
    # 우리 대화는 하나가 최대 26자라 128 이면 충분하다.
    block_size: int = 128

    # 글자 하나를 나타내는 숫자 줄의 길이 (embedding 차원).
    # 번호 하나로는 글자의 여러 면을 못 담으니 숫자를 여러 개 붙이는데, 그 개수가 이 값이다.
    # 클수록 글자를 자세히 설명할 수 있지만 계산이 늘어 느려진다 → 작은 모델이라 128 로 타협.
    n_embd: int = 128

    # 앞 글자를 참고하는 계산(attention)을 몇 갈래로 나눠서 동시에 할지.
    # 갈래마다 n_embd 줄을 똑같이 쪼개 가지므로, 이 값은 n_embd(128) 를 나누어 떨어지게 해야 한다.
    # 4 = 128 을 나누어 떨어지게 하는 값 중 작은 모델에 무난한 값 (갈래마다 32칸).
    n_head: int = 4

    # 트랜스포머 블록(참고 + 계산 한 묶음)을 몇 층 쌓을지.
    # 한 번 참고로는 글자 사이 관계를 한 겹밖에 못 봐서, 층을 쌓아 "관계의 관계" 까지 보게 한다. 층이 깊을수록 느리다.
    n_layer: int = 4

    # 학습 중 숫자 일부를 일부러 0 으로 지우는 비율 (0.1 = 10%).
    # 학습 데이터가 적으면 모델이 그대로 외워 버려서 처음 보는 질문에 못 답한다 → 일부러 지워서 특정 숫자에 기대지 못하게 한다.
    # (외우기 = 과적합. 추론할 때는 지우지 않는다)
    # 0.1 은 소수라서 타입이 정수(int)가 아니라 float 다.
    dropout: float = 0.1

    # __post_init__: dataclass 가 자동으로 만든 __init__ 이 끝난 "직후" 에 파이썬이 불러 주는 함수.
    # 값이 잘못 들어온 걸 상자를 만드는 순간 바로 잡으려고 쓴다.
    # (안 잡으면 모델을 한참 짜고 나서 attention 에서야 터져서 원인을 찾기 어렵다)
    def __post_init__(self):
        # n_embd 줄을 n_head 갈래로 "똑같이" 쪼개 쓰기 때문에 나누어 떨어지지 않으면 모델을 못 만든다.
        # (128 ÷ 4 = 32 칸씩 → 딱 떨어짐 · 128 ÷ 3 = 42.67 → 남는 칸이 생김)
        # "나누어 떨어진다" = 나눈 나머지가 0 이다.
        # assert 조건, "메시지": 조건이 거짓이면 그 자리에서 메시지와 함께 에러를 내며 멈춘다.
        # % 는 나눈 "나머지" 를 구하는 연산자. 128 % 4 = 0 (딱 나뉨) · 128 % 3 = 2 (안 나뉨)
        assert self.n_embd % self.n_head == 0, "n_embd 는 n_head 로 나누어 떨어져야 한다"


@dataclass
class TrainConfig:
    """모델을 어떻게 학습시킬지 정하는 값들. 실제 사용은 6단계 train.py 에서."""

    # 한 번에 몇 개씩 묶어 풀고 고칠지 (문서 8번 ②).
    # 하나씩 풀면 느리고 고치는 방향이 들쭉날쭉하고, 전부 한꺼번에 풀면 GPU 메모리가 터진다 → 묶음으로 푼다.
    # 클수록 방향이 안정되지만 메모리를 더 먹는다. 2 의 거듭제곱이 GPU 가 다루기 좋아서 16 ~ 64 를 많이 쓴다.
    # 32 = 그 범위의 가운데 값.
    batch_size: int = 32

    # 틀렸을 때 숫자를 한 번에 얼마나 크게 고칠지 (문서 8번 ③).
    # 너무 크면 정답을 지나쳐 튕기고, 너무 작으면 끝없이 느리다. 이런 모델의 흔한 시작값은 0.0003.
    # 0 이 많은 작은 수는 지수 표기(e)로 적으면 쓰기 쉽다. 값은 똑같다.
    # 3e-4 = 3 × 10 의 -4 제곱 = 0.0003.
    learning_rate: float = 3e-4

    # 총 몇 번 고칠지 = 학습 길이의 상한 (문서 8번 ④). 시작값이고 6단계에서 결과를 보고 조정한다.
    max_iters: int = 3000

    # 몇 번마다 한 번 "잘 배우고 있나" 점검할지 (문서 8번 ⑤). 3000 ÷ 300 = 점검 10번.
    eval_interval: int = 300

    # 점검할 때 배치를 몇 번 뽑아 평균 낼지 (문서 8번 ⑥).
    # 배치 하나로만 점수를 매기면 그 배치가 우연히 쉬웠는지 어려웠는지에 따라 들쭉날쭉하다 → 여러 번 평균 낸다.
    # 50 = 작은 모델에 무난한 값. 점검 한 번에 배치 50개를 계산한다.
    eval_iters: int = 50
