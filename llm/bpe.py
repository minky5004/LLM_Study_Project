"""BPE 토크나이저 (9단계 · 3단계 조각 4 를 여기서).

지금 토크나이저(tokenizer.py)는 글자 하나 = 번호 하나라, 번호 표에 없는 글자(hello 의 h · 😀)는 KeyError 로 거부한다.
BPE(Byte Pair Encoding — 자주 붙어 나오는 두 조각을 새 번호 하나로 합치기를 되풀이하는 방식)는
가장 작은 조각인 바이트 256종에서 출발해, 자주 나오는 묶음을 하나씩 합쳐 번호 표를 키운다.
바이트로 못 나타내는 글자는 없으니 거부도 없다.

다 만든 뒤 tokenizer.py 의 encode · decode 를 이 파일 것으로 바꿔 끼운다 (이름 · 사용법은 그대로).
"""

from llm.tokenizer import train_text


# ---- 조각 1: 글 <-> 바이트 번호 ----

def to_bytes(s):
    """문자열 -> 바이트 번호 리스트.  예) "안녕" -> [236, 149, 136, 235, 133, 149]

    컴퓨터는 글자를 UTF-8(글자를 바이트로 적는 약속)으로 저장한다 — 영어는 1바이트 · 한글은 3바이트 · 이모지는 4바이트.
    바이트 하나는 0~255 숫자 하나다. 그래서 길이 L 인 문자열이 L 보다 긴 리스트가 된다.
    """
    # 문자열을 UTF-8 약속으로 바이트 묶음으로 바꾼다 — 아래 from_bytes 의 decode(바이트 -> 글)와 짝
    b = s.encode("utf-8")
    # 결과: "안녕" -> b'\xec\x95\x88\xeb\x85\x95' (바이트 6개)
    # b 는 bytes(바이트 묶음) — 화면엔 b'\xec\x95...' 처럼 보인다.
    # list() 로 감싸면 바이트 하나하나가 0~255 숫자로 꺼내진다
    return list(b)


def from_bytes(ids):
    """바이트 번호 리스트 -> 문자열.  예) [236, 149, 136, 235, 133, 149] -> "안녕"  (to_bytes 의 정반대)"""
    # 0~255 숫자 리스트를 다시 바이트 묶음(bytes)으로 묶는다 — 0~255 밖 숫자가 있으면 ValueError
    b = bytes(ids)
    # 바이트 묶음을 UTF-8 약속으로 읽어 글로 되돌린다.
    # 모델이 만든 번호는 한글 한 글자(3바이트)의 중간에서 끊길 수 있다 — 그대로 읽으면 UnicodeDecodeError 로 멈춘다.
    # errors="replace": 글자를 못 이루는 바이트를 만나면 멈추지 않고 � 표시 하나로 바꿔 넣는다
    return b.decode("utf-8", errors="replace")


# 갔다 오면 제자리여야 한다 — 글자 단위 토크나이저와 같은 시험
if __name__ == "__main__":
    print(to_bytes("안녕"))                        # 결과: [236, 149, 136, 235, 133, 149] — '안' = 236 149 136 · '녕' = 235 133 149
    print(len("안녕"), len(to_bytes("안녕")))      # 결과: 2 6 (한글 한 글자 = 바이트 3개)
    print(to_bytes("hi"), to_bytes("😀"))          # 결과: [104, 105] [240, 159, 152, 128] — 영어 1바이트 · 이모지 4바이트 · 지금 토크나이저가 거부하는 글자도 번호가 생김
    print(from_bytes(to_bytes("안녕")))            # 결과: 안녕 (왕복)
    print(repr(from_bytes(to_bytes("안녕")[:2])))  # 결과: '�' — '안' 의 3바이트 중 2개만 · replace 가 없으면 UnicodeDecodeError
    print(len(train_text), len(to_bytes(train_text)))     # 결과: 413139 947863 (바이트로 쪼개면 약 2.3배 길어짐 — 공백 · 기호는 1바이트라 3배보다 작음)
    print(from_bytes(to_bytes(train_text)) == train_text)  # 결과: True (학습용 글 전체 왕복)


# ---- 조각 2: 이웃한 두 조각 세기 ----

def get_stats(ids):
    """번호 리스트에서 이웃한 두 번호(쌍)가 몇 번씩 붙어 나오는지 센다.

    예) [1, 2, 3, 1, 2] -> {(1, 2): 2, (2, 3): 1, (3, 1): 1}
    길이 N 인 리스트에는 이웃 쌍이 N-1 개 있다 (겹쳐서 센다 — 1,2 · 2,3 · 3,1 · 1,2).
    BPE 는 이 중 가장 많은 쌍을 다음 조각에서 새 번호 하나로 합친다.
    """
    counts = {}  # {(앞 번호, 뒤 번호): 나온 횟수} — 쌍(튜플)을 키로 쓰는 사전
    # 이웃 쌍 만들기: 원래 리스트와 "한 칸 밀린" 리스트를 zip 으로 나란히 놓고 같은 자리끼리 짝짓는다.
    #   ids        = [1, 2, 3, 1, 2]
    #   한 칸 밀린  = [2, 3, 1, 2]       <- 맨 앞 하나를 뺀 것
    #   zip 결과   = (1,2) (2,3) (3,1) (1,2)   <- 짧은 쪽 길이(4개)에서 멈춘다
    # ids[1:] = 맨 앞 하나만 빼고 끝까지 꺼내는 자르기(슬라이싱 — 리스트[시작:끝] 으로 일부만 꺼내기)
    for pair in zip(ids, ids[1:]):
        # 처음 보는 쌍은 사전에 없다 — counts[pair] 로 바로 꺼내면 KeyError.
        # 사전.get(키, 기본값) 은 키가 없으면 기본값을 돌려준다. 거기에 1 을 더해 다시 넣는다.
        # 처음 보는 쌍은 0 번 나왔다고 치고 1 을 더한다
        counts[pair] = counts.get(pair, 0) + 1
    return counts


if __name__ == "__main__":
    print(get_stats([1, 2, 3, 1, 2]))   # 결과: {(1, 2): 2, (2, 3): 1, (3, 1): 1} — 위 설명과 같다
    print(get_stats(to_bytes("안녕")))   # 결과: {(236, 149): 1, (149, 136): 1, (136, 235): 1, (235, 133): 1, (133, 149): 1} — 바이트 6개 -> 쌍 5개 · (136, 235) 는 '안' 끝과 '녕' 앞이 이어진 쌍

    # 학습용 글 전체(바이트 947,863개)의 쌍을 센다
    stats = get_stats(to_bytes(train_text))
    print(len(stats))                    # 결과: 1793 — 바이트 쌍은 256 × 256 = 65,536 가지가 가능하지만 실제로 나오는 건 1,793 종류뿐

    # 많이 나온 순으로 6개 보기.
    #   stats.items()             : (쌍, 횟수) 짝을 하나씩 꺼낸다
    #   key=lambda x: x[1]        : 정렬 기준 = 짝의 두 번째 칸(횟수). lambda 는 이름 없는 한 줄 함수 — "x 를 받아 x[1] 을 돌려준다"
    #   reverse=True              : 큰 것부터
    top = sorted(stats.items(), key=lambda x: x[1], reverse=True)[:6]
    for pair, n in top:
        # 쌍을 글로 되돌려 보면 무엇이 붙어 있는지 보인다 (repr = 공백 · 줄바꿈도 보이게)
        print(pair, n, repr(from_bytes(list(pair))))
    # 결과: (32, 236) 36471 ' �'   <- 1등은 공백 + 한글 첫 바이트 (띄어쓰기 뒤에 한글이 온다)
    #       (236, 154) 22002 '�'   <- 한글 바이트끼리 — 바이트 두 개로는 한글 글자가 안 돼 깨져 보인다
    #       (32, 235) 21943 ' �'
    #       (58, 32) 21274 ': '    <- '사용자: ' · '봇: ' 의 쌍점 + 공백 · 대화 10,637개 × 2 = 21,274 와 딱 맞는다
    #       (236, 158) 17266 '�'
    #       (236, 157) 16867 '�'


# ---- 조각 3: 가장 많은 쌍 하나를 새 번호로 합치기 ----

def merge(ids, pair, idx):
    """ids 에서 pair 가 붙어 나오는 자리를 전부 새 번호 idx 하나로 바꾼 새 리스트를 돌려준다.

    예) merge([1, 2, 3, 1, 2], (1, 2), 99) -> [99, 3, 99]
    쌍 하나가 번호 하나가 되니, 합친 자리 수만큼 리스트가 짧아진다 (길이 5 -> 3).
    원래 ids 는 건드리지 않는다 — 새 리스트 out 에 하나씩 옮겨 담는다.
    """
    out = []
    i = 0  # 지금 보고 있는 자리
    # for 대신 while: 합친 자리에선 두 칸을, 아닌 자리에선 한 칸을 건너뛰어야 해서 i 를 직접 움직인다
    while i < len(ids):
        # 지금 자리와 다음 자리가 pair 와 같은가.
        #   i < len(ids) - 1 : 맨 끝 자리에는 "다음 자리" 가 없다 — 이 검사가 먼저 있어야 ids[다음] 에서 IndexError 가 안 난다
        #                      (and 는 앞이 False 면 뒤를 아예 보지 않는다)
        # ids[i + 1] = 지금 자리(i) 바로 다음 자리의 번호
        if i < len(ids) - 1 and ids[i] == pair[0] and ids[i + 1] == pair[1]:
            out.append(idx)  # 두 번호 대신 새 번호 하나
            # 두 자리를 한꺼번에 썼으니 두 칸 건너뛴다.
            # 한 칸만 가면 방금 쓴 뒤 번호를 다시 담는다 — [1, 2, 3, 1, 2] 가 [99, 2, 3, 99, 2] 가 됨
            i += 2
        else:
            out.append(ids[i])  # 쌍이 아니면 그대로 옮긴다
            i += 1
    return out


if __name__ == "__main__":
    print(merge([1, 2, 3, 1, 2], (1, 2), 99))   # 결과: [99, 3, 99] (길이 5 -> 3)
    print(merge([5, 5, 5], (5, 5), 256))         # 결과: [256, 5] — 쌍이 겹치면 왼쪽부터 합치고, 합친 두 자리는 다시 보지 않는다

    ids = to_bytes(train_text)
    stats = get_stats(ids)
    # 가장 많이 나온 쌍 고르기.
    #   max(사전) 은 키(쌍)들 중 가장 큰 것을 고른다 — 그냥 두면 쌍 자체의 크기((236, 157) > (32, 236))로 비교한다.
    #   key= 에 "쌍을 받아 횟수를 돌려주는 함수" 를 넘기면 횟수로 비교한다.
    #   조각 2 의 lambda x: x[1] 과 같은 역할 — 사전에는 그 일을 하는 메서드가 이미 있다 (괄호 없이 함수 자체를 넘긴다)
    top_pair = max(stats, key=stats.get)
    print(top_pair, stats[top_pair])             # 결과: (32, 236) 36471 — 조각 2 의 정렬 1등과 같다

    # 새 번호는 256 — 0~255 는 바이트가 이미 쓰고 있어서 그다음 번호부터
    merged = merge(ids, top_pair, 256)
    print(len(ids), len(merged), len(ids) - len(merged))   # 결과: 947863 911392 36471 — 합친 횟수만큼 짧아짐 (약 3.8%)
    print(merged.count(256))                               # 결과: 36471 — 쌍이 나온 횟수와 같다

    # 합친 뒤 다시 세면 순위가 바뀐다 — 다음 합치기 후보
    stats2 = get_stats(merged)
    print(sorted(stats2.items(), key=lambda x: x[1], reverse=True)[:3])
    # 결과: [((32, 235), 21943), ((236, 154), 21491), ((236, 157), 14061)]
    #       (32, 235) 가 새 1등 · (236, 154) 는 22002 -> 21491 로 줄었다 — 그 앞의 236 일부가 256 으로 합쳐져 사라져서


# ---- 조각 4: 합치기 되풀이 = BPE 학습 · 합치기 표 ----

def train(text, vocab_size):
    """글을 보고 합치기 표를 배운다.  세기(조각 2) -> 1등 고르기 -> 합치기(조각 3) 를 정한 횟수만큼 되풀이.

    돌려주는 것 두 개:
      merges : 합치기 표 {(앞 번호, 뒤 번호): 새 번호} — 합친 순서대로 쌓인다. 조각 5 의 encode 가 새 글에 이 순서 그대로 합친다
      ids    : 다 합친 뒤의 번호 리스트 — 글이 얼마나 짧아졌는지 확인용
    vocab_size = 번호 표 전체 크기(바이트 256 + 새로 만든 번호 수).
    """
    ids = to_bytes(text)  # 출발점: 바이트 번호 리스트 (0~255)

    # 몇 번 합치나.  번호 표는 바이트 256장에서 시작해 한 번 합칠 때마다 한 장씩 는다.
    # vocab_size 장이 되려면 그 차이만큼 합친다 — 1024 가 목표면 768번
    num_merges = vocab_size - 256

    merges = {}  # 합치기 표 — 쌍을 키로: encode 때 "이 쌍 합치나? 합치면 몇 번?" 을 쌍으로 바로 찾게
    # i = 0, 1, 2, ... num_merges-1 — 몇 번째 합치기인지
    for i in range(num_merges):
        stats = get_stats(ids)                   # 지금 리스트의 이웃 쌍 세기 (조각 2)
        pair = max(stats, key=stats.get)         # 가장 많이 나온 쌍 (조각 3 과 같은 줄)

        # 새 번호 — 0~255 는 바이트 몫이라 첫 번째(i=0)는 256, 두 번째(i=1)는 257, ...
        idx = i + 256

        # ids 에서 pair 를 idx 로 합친다 (조각 3 의 merge).
        # merge 는 원래 리스트를 건드리지 않고 "새 리스트" 를 돌려준다 — ids 에 다시 담아야 다음 바퀴의 get_stats 가 합친 결과 위에서 센다
        # (merged 같은 다른 이름에 담으면 매 바퀴 처음 바이트를 세서 같은 쌍만 1등이 된다)
        ids = merge(ids, pair, idx)

        # 합치기 표에 "pair 는 idx 로 합쳤다" 를 적는다 — {(앞, 뒤): 새 번호} · 사전은 넣은 순서를 기억해 합친 순서도 남는다
        merges[pair] = idx

    return merges, ids


if __name__ == "__main__":
    import time

    # 작은 예로 손 계산과 맞춰 보기 — 'a' = 97 · 'b' = 98 · 'c' = 99 · 'd' = 100
    m, ids = train("aaabdaaabac", 256 + 3)   # 3번 합치기
    print(m)     # 결과: {(97, 97): 256, (256, 97): 257, (257, 98): 258} — 'aa' -> 256 · 256+'a' -> 257 · 257+'b' -> 258 (앞에서 합친 것을 또 합침)
                 #       2바퀴는 (256, 97) 과 (97, 98) 이 2번씩 동점 — max 는 먼저 나온 쪽을 고른다
    print(ids)   # 결과: [258, 100, 258, 97, 99] — 'aaab' 가 258 하나로 · 11칸 -> 5칸 (손 계산과 같다)

    # 학습용 글 전체로 20번 합치기 — 한 바퀴마다 95만 개를 두 번(세기 · 합치기) 훑어서 시간이 걸린다
    t = time.perf_counter()                     # 지금 시각(초) — 끝난 시각에서 빼면 걸린 시간
    merges, ids = train(train_text, 256 + 20)
    print(f"{time.perf_counter() - t:.1f}초")   # 결과: 3.8초 · 6.1초 (두 번 실행 — 실행마다 다름) — 한 바퀴 약 0.2~0.3초 · 1024 (768번) 이면 몇 분 · 조각 6 에서 다시 잰다
    print(len(to_bytes(train_text)), len(ids))  # 결과: 947863 672721 — 바이트 길이 -> 20번 합친 뒤 길이 (약 29% 짧아짐)
    # 합친 순서대로 처음 5개 — 256 번 이상이 쌍 안에 나오면 "앞에서 합친 것을 또 합쳤다" 는 뜻
    print(list(merges.items())[:5])             # 결과: [((32, 236), 256), ((32, 235), 257), ((236, 154), 258), ((236, 157), 259), ((130, 172), 260)]
                                                #       1 · 2등은 조각 3 에서 본 (32, 236) · (32, 235) 그대로 — 아직 256 이상 번호끼리의 합치기는 처음 5개엔 없다

