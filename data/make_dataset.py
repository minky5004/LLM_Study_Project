"""토이 학습 데이터 생성기.

템플릿(주제별 질문 · 답 후보)에서 무작위로 골라 짧은 대화를 수천 개 만들어 data/train.txt 로 저장한다.
실행: uv run python data/make_dataset.py
"""

# random: 표준 라이브러리의 난수 모듈. 리스트에서 무작위로 하나 고르는 기능 등이 들어 있다
import random

# pathlib.Path: 파일 경로를 문자열 대신 객체로 다루게 해 주는 표준 라이브러리.
# 윈도우(\) · 맥/리눅스(/) 구분자 차이를 알아서 처리해 준다
from pathlib import Path

# 대화 개수. 많을수록 모델이 패턴을 안정적으로 배우고, 적을수록 학습이 빨리 끝난다.
# 토이 데이터라 수천 개면 충분하다 (글자 수로는 대략 10~15만 자)
NUM_DIALOGS = 3000

# 주제별 (질문 후보들, 답 후보들). 같은 주제 안에서만 질문과 답을 짝지어서,
# 모델이 "이런 질문이 나오면 이런 종류의 답이 온다" 는 규칙을 배울 수 있게 한다.
# 글자 종류를 적게 유지하려고 문장을 일부러 짧고 단순하게 썼다 (3단계 글자 단위 토크나이저의 vocab 이 작아짐)
TOPICS = [
    (
        ["안녕", "안녕하세요", "반가워"],
        ["안녕하세요", "반가워요", "어서 와요"],
    ),
    (
        ["이름이 뭐야", "너는 누구야", "누구세요"],
        ["나는 작은 모델이에요", "나는 물고기예요", "이름은 아직 없어요"],
    ),
    (
        ["오늘 날씨 어때", "날씨 어때", "비 와"],
        ["맑아요", "조금 흐려요", "비가 와요"],
    ),
    (
        ["뭐 먹었어", "배고파", "밥 먹었어"],
        ["물풀을 먹었어요", "아직 안 먹었어요", "맛있게 먹었어요"],
    ),
    (
        ["잘 자", "졸려", "이제 자자"],
        ["잘 자요", "좋은 꿈 꿔요", "내일 봐요"],
    ),
]


def make_dialog() -> str:
    """대화 하나를 문자열로 만든다.

    반환 예: "사용자: 안녕\\n봇: 반가워요\\n" (줄 두 개)
    """
    # 주제 하나를 무작위로 뽑는다. 결과는 (질문 후보 리스트, 답 후보 리스트) 튜플.
    # random.choice(리스트) 는 리스트에서 원소 하나를 무작위로 돌려주는 함수다
    questions, answers = random.choice(TOPICS)

    # 뽑은 주제 안에서 질문 하나 · 답 하나를 각각 고른다
    q = random.choice(questions)
    a = random.choice(answers)

    # 두 줄짜리 대화 문자열로 조립한다.
    # 앞에 f 를 붙인 문자열(f-string)은 {변수} 자리에 그 변수의 값을 끼워 넣는다.
    # 줄바꿈은 \n. "사용자:" · "봇:" 은 나중에 모델이 누가 말하는지 구분하는 표지가 된다
    return f"사용자: {q}\n봇: {a}\n"


def main() -> None:
    # 실행할 때마다 같은 데이터가 나오게 난수 시작점을 고정한다.
    # 그래야 "데이터가 달라서 결과가 달라졌나?" 를 의심하지 않아도 된다
    random.seed(0)

    # 대화 NUM_DIALOGS 개를 리스트로 모은다 (리스트 컴프리헨션: for 를 한 줄로 쓴 문법).
    # 밑줄 _ 는 "반복 횟수만 필요하고 값은 안 쓴다" 는 관례적 표시
    dialogs = [make_dialog() for _ in range(NUM_DIALOGS)]

    # 대화 사이에 빈 줄이 하나 들어가도록 "\n" 으로 이어 붙여 하나의 긴 텍스트로 만든다.
    # 각 대화가 이미 \n 으로 끝나므로, 사이에 \n 을 더 붙이면 빈 줄 한 개가 생긴다
    text = "\n".join(dialogs)

    # 이 파일(make_dataset.py)이 있는 폴더(data/) 옆에 train.txt 를 만든다.
    # __file__ 은 지금 실행 중인 파일의 경로, .parent 는 그 파일이 든 폴더
    out_path = Path(__file__).parent / "train.txt"

    # 파일에 쓴다. "w" 는 쓰기 모드(있으면 덮어씀).
    # 윈도우는 encoding 을 안 적으면 한글 지원이 약한 옛 기본 인코딩(cp949)으로 저장돼서,
    # 다른 곳에서 읽을 때 글자가 깨질 수 있다 → 한글은 항상 인코딩을 명시한다
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)

    # 결과 요약 출력: 대화 개수 · 전체 글자 수 · 서로 다른 글자 종류(= 글자 단위 토크나이저의 vocab_size 후보)
    print(f"저장: {out_path}")
    print(f"대화 {NUM_DIALOGS}개 · 글자 {len(text)}자 · 글자 종류 {len(set(text))}개")


# 이 파일을 직접 실행했을 때만 main() 을 부른다 (다른 파일에서 import 할 때는 실행 안 됨)
if __name__ == "__main__":
    main()
