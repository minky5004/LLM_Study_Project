"""토이 학습 데이터 생성기.

템플릿(주제별 질문 · 답 후보)에서 무작위로 골라 짧은 대화를 수천 개 만들어 data/train.txt 로 저장한다.
지금은 조각 3까지: 대화 하나를 만드는 make_dialog() + 3000개를 모아 파일로 저장하는 main().
"""

# random: 표준 라이브러리의 난수 모듈. 리스트에서 무작위로 하나 고르는 기능 등이 들어 있다.
import random

# pathlib.Path: 파일 경로를 문자열 대신 객체로 다루게 해 주는 표준 라이브러리.
# 윈도우(\) · 맥/리눅스(/) 구분자 차이를 알아서 처리해 준다 (문서 8번).
from pathlib import Path

# 대화 개수. 많을수록 모델이 패턴을 안정적으로 배우고, 적을수록 학습이 빨리 끝난다.
# 토이 데이터라 수천 개면 충분하다 (글자 수로는 대략 6~7만 자).
NUM_DIALOGS = 3000

# 주제별 (질문 후보들, 답 후보들). 같은 주제 안에서만 질문과 답을 짝지어서,
# 모델이 "이런 질문이 나오면 이런 종류의 답이 온다" 는 규칙을 배울 수 있게 한다 (문서 2단계 읽을 것 3번).
# 글자 종류를 적게 유지하려고 문장을 일부러 짧고 단순하게 썼다 (3단계 글자 단위 토크나이저의 vocab 이 작아짐).
TOPICS = [
    (
        ["안녕", "안녕하세요", "반가워"],
        ["안녕하세요", "반가워요", "어서 와요"],
    ),
    (
        ["이름이 뭐야", "너는 누구야", "누구세요"],
        ["나는 작은 모델이에요", "나는 물고기예요", "이름은 아직 없어요"],
    ),
    (
        ["오늘 날씨 어때", "날씨 어때", "비 와"],
        ["맑아요", "조금 흐려요", "비가 와요"],
    ),
    (
        ["뭐 먹었어", "배고파", "밥 먹었어"],
        ["물풀을 먹었어요", "아직 안 먹었어요", "맛있게 먹었어요"],
    ),
    (
        ["잘 자", "졸려", "이제 자자"],
        ["잘 자요", "좋은 꿈 꿔요", "내일 봐요"],
    ),
]


def make_dialog() -> str:
    """대화 하나를 문자열로 만든다.

    반환 예: "사용자: 안녕\\n봇: 반가워요\\n" (줄 두 개)
    """
    # 주제 하나를 무작위로 뽑는다. 결과는 (질문 후보 리스트, 답 후보 리스트) 두 개짜리 묶음이다.
    # 그 묶음을 questions, answers 두 이름에 나눠 받는다 (앞의 리스트 → questions · 뒤의 리스트 → answers).
    # random.choice(리스트) = 리스트에서 원소 하나를 무작위로 돌려주는 함수.
    questions, answers = random.choice(TOPICS)
    # 결과 (main 에서 시드 0 으로 처음 부르면): questions = ['뭐 먹었어', '배고파', '밥 먹었어']
    #                                            answers   = ['물풀을 먹었어요', '아직 안 먹었어요', '맛있게 먹었어요']

    # 뽑은 주제 안에서 질문 하나 · 답 하나를 각각 고른다.
    # 둘 다 같은 주제의 리스트에서 뽑으므로 짝이 항상 맞는다.
    q = random.choice(questions)
    a = random.choice(answers)
    # 결과: q = '배고파' · a = '물풀을 먹었어요'   (둘 다 같은 주제에서 나왔으니 짝이 맞는다)

    # 두 줄짜리 대화 문자열로 조립한다. {변수} 자리에 값을 끼워 넣는 문자열 형식을 쓴다 (문서 4번).
    # 줄바꿈은 \n. 끝에도 \n 을 붙여서 대화가 줄바꿈으로 끝나게 한다.
    # "사용자:" · "봇:" 은 나중에 모델이 누가 말하는지 구분하는 표지가 된다.
    # 따옴표 앞의 f 가 있어야 {q} · {a} 에 값이 끼워진다 (f-string). 없으면 {q} 글자가 그대로 나온다.
    return f"사용자: {q}\n봇: {a}\n"
    # 결과: '사용자: 배고파\n봇: 물풀을 먹었어요\n'   (print 하면 두 줄로 보이고, 끝의 \n 때문에 아래에 빈 줄이 하나 생긴다)


def main() -> None:
    # 실행할 때마다 같은 데이터가 나오게 난수 시작점(시드)을 고정한다.
    # 그래야 "코드를 바꿔서 결과가 달라졌나, 데이터가 달라서 달라졌나" 를 가릴 수 있다 (문서 5번).
    # 0 은 아무 숫자나 하나로 정한 시작점이다 (값 자체에 뜻은 없다).
    random.seed(0)
    # 결과: 출력 없음. 이 줄 이후 random 이 뽑는 순서가 실행할 때마다 똑같아진다

    # 대화 NUM_DIALOGS 개를 리스트로 모은다.
    # 리스트 컴프리헨션 = "반복하며 결과를 리스트에 담는" 코드를 한 줄로 쓴 문법: [식 for 변수 in 반복할것] (문서 6번 ②).
    # 반복 횟수만 필요하고 반복 변수의 값은 안 쓰므로, 변수 이름은 "안 쓴다" 는 관례적 표시인 밑줄 한 글자로 쓴다.
    dialogs = [make_dialog() for _ in range(NUM_DIALOGS)]
    # 결과: 대화 3000개가 든 리스트
    #   dialogs[0] = '사용자: 배고파\n봇: 물풀을 먹었어요\n'
    #   dialogs[1] = '사용자: 비 와\n봇: 조금 흐려요\n'

    # 대화 사이에 빈 줄이 하나 들어가도록 줄바꿈 글자(백슬래시 n)로 이어 붙여 하나의 긴 글로 만든다.
    # 각 대화가 이미 줄바꿈으로 끝나므로, 사이에 줄바꿈을 하나 더 넣으면 빈 줄 한 개가 생겨서 대화끼리 구분된다 (문서 6번 ⑤).
    # join(리스트) = 리스트의 항목들을 앞의 구분글자로 이어 붙이는 문자열 메서드.
    text = "\n".join(dialogs)
    # 결과: 하나의 긴 글. 대화 사이에 빈 줄 한 개가 들어간다
    #   '사용자: 배고파\n봇: 물풀을 먹었어요\n\n사용자: 비 와\n봇: 조금 흐려요\n\n사용자: 배고파\n...'

    # 이 파일(make_dataset.py)이 든 폴더(data/) 안에 train.txt 를 만든다 (문서 8번).
    # __file__ 은 지금 실행 중인 파일의 경로 · .parent 는 그 파일이 든 폴더 · / 는 경로를 이어 붙이는 연산자.
    # 어느 폴더에서 실행하든 항상 같은 자리에 만들어진다.
    out_path = Path(__file__).parent / "train.txt"
    # 결과: .../LLM_Study_Project/data/train.txt  (이 파일 옆 data 폴더 안의 train.txt)

    # 파일에 쓴다. "w" 는 쓰기 모드(이미 있으면 덮어씀).
    # with 는 블록이 끝나면 파일을 자동으로 닫아 준다 (닫아야 쓴 내용이 디스크에 확실히 남는다).
    # 윈도우는 encoding 을 안 적으면 한글 지원이 약한 옛 기본 인코딩(cp949)으로 저장돼서
    # 다른 곳에서 읽을 때 글자가 깨질 수 있다 → 한글은 항상 인코딩을 명시한다 (문서 7번).
    # utf-8 = 전 세계 글자를 담는 표준 인코딩.
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    # 결과: data/train.txt 에 한글이 깨지지 않게 저장된다 (같은 이름의 파일이 있으면 덮어쓴다)

    # 결과 요약 출력: 대화 개수 · 전체 글자 수 · 서로 다른 글자 종류.
    # set(text) 는 글 안의 글자를 중복 없이 모은 것 → 그 개수가 글자 단위 토크나이저의 vocab_size 후보 (3단계).
    print(f"저장: {out_path}")
    print(f"대화 {NUM_DIALOGS}개 · 글자 {len(text)}자 · 글자 종류 {len(set(text))}개")
    # 결과 (터미널에 출력):
    #   저장: C:\...\LLM_Study_Project\data\train.txt
    #   대화 3000개 · 글자 65572자 · 글자 종류 69개


# 이 파일을 직접 실행했을 때만 main() 을 부른다 (다른 파일에서 import 할 때는 실행 안 됨).
if __name__ == "__main__":
    main()

